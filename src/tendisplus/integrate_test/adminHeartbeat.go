package main

import (
	"flag"
	"math"
	"strconv"
	"time"

	"integrate_test/util"

	"github.com/ngaut/log"
)

func testAutoGenerateHeartbeatTimestamp() {
	*util.Optype = "set"
	interval := 1
	clusterNodeNum := 1
	cfgArgs := map[string]string{
		"generate-heartbeat-binlog-interval": strconv.Itoa(interval),
	}
	servers, predixy, _ := startCluster(
		"127.0.0.1", 42000, clusterNodeNum, cfgArgs, util.GetCurrentDirectory(), "")

	for i := range *servers {
		checkAutoGeneratedHeartbeat(&(*servers)[i], interval)
	}

	log.Infof("adminHeartbeat.go passed. command : %s", *util.Optype)
	stopCluster(servers, clusterNodeNum, predixy)
}

func checkAutoGeneratedHeartbeat(srv *util.RedisServer, interval int) {
	cli := createClient(srv)
	for i := 0; i < 20; i++ {
		r, err := cli.Cmd("adminget", "auto_generated_heartbeat", "withttl", "1").Array()
		if err != nil {
			log.Fatalf("port %d adminget auto_generated_heartbeat withttl 1 errmsg:%v ret:%v",
				srv.Port, err, r)
		}
		// get store 0 metric
		lr, _ := r[0].Array()
		store0ResultDate, err := lr[1].Str()
		if err != nil {
			log.Fatalf("port %d adminget auto_generated_heartbeat withttl 1 errmsg:%v ret:%v",
				srv.Port, err, r)
		}
		log.Infof("port %d heartbeat date: %v", srv.Port, store0ResultDate)
		store0ResultTS, err := lr[2].Int64()
		if err != nil {
			log.Fatalf("port %d adminget auto_generated_heartbeat withttl 1 errmsg:%v ret:%v",
				srv.Port, err, r)
		}
		currentTS := time.Now().UnixNano() / int64(time.Millisecond) // get millisecond timestamp
		if math.Abs(float64(currentTS-store0ResultTS)) > float64(2*interval*1000) {
			log.Fatalf("port %d heartbeat admincmd hasn't updated for two intervals", srv.Port)
		}
		log.Infof("port %d %v %v", srv.Port, currentTS, store0ResultTS)
		time.Sleep(1 * time.Second)
	}
}

func main() {
	log.SetFlags(log.LstdFlags | log.Lmicroseconds | log.Lshortfile)
	flag.Parse()
	// rand.Seed(time.Now().UnixNano())
	testAutoGenerateHeartbeatTimestamp()
}
